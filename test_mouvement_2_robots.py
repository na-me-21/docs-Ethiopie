def rotation_L():
    """
    All the rotation function are parts of the memory for the robot. 
    rotation_X modify the dictionary 'cube_memory' by applying an X rotation.

    """
    global cube_memory
    
    # We save how the cube is actually looking befor modifying it 
    previous = cube_memory.copy()
    
    cube_memory["F"] = previous["D"] # down to front
    cube_memory["B"] = previous["U"] # up to back 
    cube_memory["D"] = previous["R"] # right to down
    cube_memory["U"] = previous["L"] # left to up
    cube_memory["L"] = previous["B"] # back to left
    cube_memory["R"] = previous["F"] # front to right
    return

