def to_robodk(move_liste):
    instruction = []
    for l in move_liste :
        move = details_movement[l]
        for i in range(len(move)):
            if move[i][1]=='/':
                instruction.append((move[i],0))
                
            elif move[i][0]=='[':
                j = 0
                line = []
                while move[i][j] != ']':
                    k=j+1
                    coordonnee = ""
                    while move[i][k] != ',' and move[i][k] != ']':
                        coordonnee += move[i][k]
                        k+=1
                    line.append(float(coordonnee))
                    j = k
            
                instruction.append(line)
                
            elif move[i][0]=='t':
                if move[i][11]=='4':
                    instruction.append('Fermer_pince_1')
                elif move[i][11]=='8':
                    instruction.append('Ouvrir_pince_1')
    
    
    return instruction


